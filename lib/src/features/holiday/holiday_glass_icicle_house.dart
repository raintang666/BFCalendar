void _paintIcicle(
  Canvas canvas,
  double x,
  double y,
  double width,
  double length,
  double angle,
  double intensity,
  double glint,
) {
  canvas.save();
  canvas.translate(x, y);
  canvas.rotate(angle);
  canvas.scale(width / 25, length / 105);
  canvas.drawPath(
    _icicleOutline,
    Paint()
      ..shader = ui.Gradient.linear(
        const Offset(-13, 9),
        const Offset(10, 49),
        [
          _a(const Color(0xFFC3ECFA), .92 * intensity),
          _a(const Color(0xFF74B8D8), .79 * intensity),
          _a(const Color(0xFF6CA9CC), .48 * intensity),
          _a(const Color(0xFFB8E2F6), .87 * intensity),
        ],
        const [0, .25, .56, 1],
      ),
  );
  final facet = Paint()..color = _a(const Color(0xFF45779D), .54 * intensity);
  canvas.drawPath(_icicleRightFacet, facet);
  canvas.drawPath(
    _icicleLeftFacet,
    facet..color = _a(const Color(0xFFDCF7FF), (.27 + .51 * glint) * intensity),
  );
  _stroke(
    canvas,
    _icicleOutline,
    const Color(0xFFCBEFF8),
    .66 * intensity,
    .88,
  );
  _stroke(
    canvas,
    _icicleRidges,
    const Color(0xFFCDF1FF),
    (.54 + .38 * glint) * intensity,
    1.15,
  );
  _stroke(
    canvas,
    _icicleFractures,
    const Color(0xFFE7F7FC),
    .49 * intensity,
    1.09,
  );
  canvas.restore();
}

