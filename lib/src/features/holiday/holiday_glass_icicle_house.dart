final _dahanSnowLayers =
    const [
          (
            count: 64,
            left: 176.0,
            span: 442.0,
            minSize: 1.3,
            sizeRange: 2.8,
            color: Color(0xFFCAE0F4),
          ),
          (
            count: 44,
            left: 194.0,
            span: 412.0,
            minSize: 3.9,
            sizeRange: 4.6,
            color: Color(0xFFDDEFFC),
          ),
          (
            count: 38,
            left: 221.0,
            span: 395.0,
            minSize: 7.1,
            sizeRange: 7.1,
            color: Color(0xFFEAF7FF),
          ),
        ].indexed
        .map((entry) {
          final (depth, style) = entry;
          return (
            color: style.color,
            flakes: List.generate(style.count, (i) {
              final seed = 24100 + depth * 700 + i * 8;
              return (
                x: style.left + holidayRandom(seed) * style.span,
                offset: holidayRandom(seed + 1),
                size: style.minSize + holidayRandom(seed + 2) * style.sizeRange,
                fallRate:
                    2 + holidayRandom(seed + 3).round() + (depth == 2 ? 1 : 0),
                sway: holidayRandom(seed + 4) * _tau,
                turns: holidayRandom(seed + 5) > .5 ? 1.0 : -1.0,
                opacity: .38 + holidayRandom(seed + 6) * .43,
                soft: holidayRandom(seed + 7) < .25,
              );
            }),
          );
        })
        .toList(growable: false);

void _dahanSnowfall(Canvas canvas, double t, int depth) {
  final layer = _dahanSnowLayers[depth];
  final air = .80 + .20 * math.sin(_phase(t, 2, -.4));
  for (final flake in layer.flakes) {
    final u = (flake.offset + t / _loop * flake.fallRate) % 1;
    final x =
        flake.x -
        (u - .42) * (52 + depth * 21) * air +
        math.sin(flake.sway + u * 8 + _phase(t)) * (8 + depth * 3.5);
    final y = -24 + u * (280 + depth * 14);
    final visible = holidaySmooth(0, .09, u) * (1 - holidaySmooth(.85, 1, u));
    final textSpace =
        1 - (1 - holidaySmooth(169, 255, x)) * holidaySmooth(132, 174, y);
    final overEaves =
        holidaySmooth(340, 380, x) *
        (1 - holidaySmooth(503, 541, x)) *
        holidaySmooth(103, 126, y) *
        (1 - holidaySmooth(191, 227, y));
    final opacity =
        flake.opacity *
        visible *
        textSpace *
        (.64 + .18 * depth) *
        (1 - .55 * overEaves);
    if (depth == 0 || (depth == 1 && flake.soft)) {
      _ellipse(
        canvas,
        x,
        y,
        flake.size * .78,
        flake.size * .64,
        layer.color,
        opacity,
        -.3,
      );
      continue;
    }
    if (depth == 2 && flake.soft) {
      _glow(canvas, x, y, flake.size * 1.35, layer.color, opacity * .29);
    }
    final tilt = flake.sway + _phase(t, flake.turns) + .32 * math.sin(u * _tau);
    canvas.save();
    canvas.translate(x, y);
    canvas.rotate(tilt);
    canvas.scale(
      flake.size,
      flake.size * (.84 + .16 * math.cos(_phase(t, 2, flake.sway))),
    );
    _stroke(
      canvas,
      _pineSnowCrystal,
      layer.color,
      opacity,
      depth == 2 ? .148 : .159,
    );
    canvas.restore();
  }
}

void _dahan(Canvas canvas, double t) {
  final frozen = holidayIcicleGrowth(t, .75);
  final shine = holidayIcicleGlint(t, .25);
  _glow(canvas, 458, 102, 206, const Color(0xFF639ED9), .23 + .13 * frozen);
  _glow(canvas, 424, 153, 156, const Color(0xFF9CDCF6), .055 + .15 * shine);
  _dahanSnowfall(canvas, t, 0);
  _deepSnowTree(canvas, const Offset(309, 211), 66, 16, .40, .86);
  _deepSnowTree(canvas, const Offset(549, 214), 87, 23, .48, .9);
  _deepSnowTree(canvas, const Offset(569, 220), 62, 16, .32, .88);
  _dahanSnowfall(canvas, t, 1);

  canvas.save();
  canvas.translate(424, 182);
  canvas.drawPath(_frozenHouseDrift, _frozenHouseDriftPaint);
  _ellipse(canvas, 6, 42, 90, 10, const Color(0xFF2D3A4D), .32, -.10);
  _paintFrozenHouse(canvas);
  final paint = Paint()..color = const Color(0xFF635763);
  canvas.drawPath(_frozenHouseChimney, paint);
  canvas.drawPath(
    _frozenHouseChimneyShade,
    paint..color = const Color(0xFF394453),
  );
  _line(canvas, 4, -126, 22, -131, const Color(0xFFD0EAF7), .92, 3.9);
  _line(canvas, 22, -131, 30, -125, const Color(0xFFAFCCE4), .86, 3.2);
  canvas.drawPath(_frozenHouseStep, paint..color = const Color(0xFFA4AFBD));
  _line(canvas, 44, 47, 84, 41, const Color(0xFFCCDEE9), .84, 1.5);

  for (final (i, ice) in _eavesIcicles.indexed) {
    final growth = holidayIcicleGrowth(t, ice.start);
    final glint = holidayIcicleGlint(t, i * .18);
    final y = _frozenEaveY(ice.x) + 4;
    final length = ui.lerpDouble(5 + ice.length * .06, ice.length, growth)!;
    _paintIcicle(
      canvas,
      ice.x,
      y,
      ice.width * (.59 + .41 * growth),
      length,
      ice.tilt,
      .68 + .3 * growth,
      glint,
    );
    if (i.isEven) {
      _paintIcicle(
        canvas,
        ice.x + 7.5,
        y - .9,
        ice.width * .48,
        length * .51,
        ice.tilt + .14,
        .61 + .14 * growth,
        glint,
      );
    }
  }
  _paintFrozenRoof(canvas);
  canvas.restore();

  final gust =
      .66 * (1 - holidaySmooth(0, 1.4, t)) +
